"""The evidence-gathering branch: what `needs_more_data` actually does.

In the original implementation `needs_more_data` was generated by the Diagnostician
and then never read - the loop acted on a 0.2-confidence diagnosis exactly as it
acted on a 0.95 one. That is the single most important missing behaviour in a naive
agent loop, because "decide what you need to know next" is the difference between an
agent and a function call.

`silent_config_drift` is the scenario built to exercise it: the cause is invisible
in metrics, logs, traces and deploys, and appears ONLY in the config diff. An agent
that cannot request a tool cannot solve it, so these tests fail loudly if the branch
is ever disconnected again.
"""

from __future__ import annotations

import asyncio

import pytest

from src.loop import IncidentManager
from src.models.state import EventType, HaltReason, IncidentState, IncidentStatus, TelemetryTool
from src.sandbox.scenarios import SCENARIOS
from src.sandbox.stack import SandboxStack
from src.tools.observability import DEFAULT_BUNDLE, TOOL_REGISTRY, describe_tools, observe_all, run_tools

from ._fake_llm import FakeLLMClient
from .conftest import drive


def test_the_cause_is_genuinely_invisible_in_the_default_bundle():
    """If the default telemetry gave it away, the scenario would prove nothing."""
    scenario = SCENARIOS["silent_config_drift"]
    stack = SandboxStack(scenario=scenario, service=scenario.default_service)
    default = str(observe_all(stack))
    assert "db.pool.maxSize" not in default, "the cause must not be in the free telemetry"
    assert "db.pool.maxSize" in str(stack.config_diff()), "but it must be in the config diff"


def test_agent_requests_tools_and_then_solves_it():
    manager = IncidentManager(llm=FakeLLMClient())
    state = asyncio.run(drive(manager, "silent_config_drift", "approve"))
    assert state.evidence_rounds >= 1, "the agent should have asked for more evidence"
    assert state.evidence, "tool results should be recorded on the state"
    assert any("get_config_diff" in key for key in state.evidence)
    assert state.status == IncidentStatus.RESOLVED
    # And the second diagnosis should be the confident one.
    assert state.diagnostics[-1]["confidence"] >= 0.6


@pytest.mark.loop_engine
def test_evidence_request_and_result_are_both_streamed():
    """A learner watching the console should see the agent decide to look something up."""
    manager = IncidentManager(llm=FakeLLMClient())
    state = asyncio.run(drive(manager, "silent_config_drift", "approve"))
    kinds = [e.type for e in state.events]
    assert EventType.EVIDENCE_REQUEST in kinds
    assert EventType.EVIDENCE_GATHERED in kinds
    request = next(e for e in state.events if e.type == EventType.EVIDENCE_REQUEST)
    assert request.payload["tools"], "the request must name the tools"
    assert request.payload["reason"], "and say why"


def test_evidence_rounds_are_bounded(env):
    """An unbounded 'I need more data' loop is an unbounded loop.

    With rounds disabled, a low-confidence diagnosis must escalate rather than
    silently proceed on a guess.
    """
    env(IC_MAX_EVIDENCE_ROUNDS="0")
    manager = IncidentManager(llm=FakeLLMClient())
    state = asyncio.run(drive(manager, "silent_config_drift", "approve"))
    assert state.evidence_rounds == 0
    assert state.status == IncidentStatus.ESCALATED
    assert state.halt_reason == HaltReason.LOW_CONFIDENCE


def test_confident_scenarios_do_not_waste_budget_on_evidence():
    """Requesting evidence you do not need is a cost bug, not a safety feature."""
    manager = IncidentManager(llm=FakeLLMClient())
    state = asyncio.run(drive(manager, "bad_deploy", "approve"))
    assert state.evidence_rounds == 0


# --- the tool registry itself ----------------------------------------------


def test_every_telemetry_tool_is_registered_and_callable():
    """The Diagnostician's schema is bound to this enum, so a gap here is a crash."""
    scenario = SCENARIOS["db_pool_exhaustion"]
    stack = SandboxStack(scenario=scenario, service=scenario.default_service)
    for tool in TelemetryTool:
        assert tool in TOOL_REGISTRY, f"{tool} is requestable but not implemented"
        result = TOOL_REGISTRY[tool].fn(stack)
        assert result is not None


def test_tool_batch_is_capped_per_round():
    """Without a cap, a low-confidence agent can request everything every round."""
    scenario = SCENARIOS["db_pool_exhaustion"]
    stack = SandboxStack(scenario=scenario, service=scenario.default_service)
    results = run_tools(stack, list(TelemetryTool), limit=2)
    assert len([k for k in results if not k.startswith("_")]) == 2
    assert "_truncated" in results, "dropped requests must be visible, not silent"


def test_a_failing_tool_degrades_evidence_instead_of_killing_the_loop(monkeypatch):
    """A telemetry backend being down is normal during an incident."""
    scenario = SCENARIOS["db_pool_exhaustion"]
    stack = SandboxStack(scenario=scenario, service=scenario.default_service)
    monkeypatch.setattr(stack, "pool_stats", lambda: (_ for _ in ()).throw(RuntimeError("prometheus down")))
    result = run_tools(stack, [TelemetryTool.POOL_STATS])
    assert "error" in result["get_pool_stats"]


def test_tool_catalog_excludes_what_the_agent_already_has():
    """No point offering a tool whose output is already in the prompt."""
    catalog = describe_tools()
    for tool in DEFAULT_BUNDLE:
        assert tool.value not in catalog
    assert TelemetryTool.CONFIG_DIFF.value in catalog


def test_ground_truth_is_never_leaked_to_the_agent():
    """`faulted` is the answer key. Exposing it would make every scenario trivial."""
    scenario = SCENARIOS["memory_leak"]
    stack = SandboxStack(scenario=scenario, service=scenario.default_service)
    assert "faulted" not in observe_all(stack)["metrics"]


def test_ground_truth_is_not_leaked_by_the_on_demand_metrics_tool():
    """The bundle filter alone is not enough: the Diagnostician can re-request
    `get_metrics` via `needs_more_data`, and that path used to return the raw
    snapshot - answer key included - straight into `state.evidence` and the next
    prompt."""
    scenario = SCENARIOS["memory_leak"]
    stack = SandboxStack(scenario=scenario, service=scenario.default_service)
    result = run_tools(stack, [TelemetryTool.METRICS])
    assert "faulted" not in result["get_metrics"]


def test_ground_truth_is_not_leaked_by_action_results():
    """`metrics_after` rides along on every executed action's result, which lands
    in `state.actions` - and from there in the action-history prompt block and the
    API. It must be the agent-visible snapshot, not the raw one."""
    scenario = SCENARIOS["bad_deploy"]
    stack = SandboxStack(scenario=scenario, service=scenario.default_service)
    for action in (*scenario.plan, "clear_cache"):  # the plan, plus a wrong action
        result = stack.apply_action(action)
        assert "faulted" not in result.get("metrics_after", {}), action


def test_evidence_is_sanitized_like_any_other_telemetry():
    """On-demand tool output is untrusted input too - an easy seam to forget."""
    from src.guardrails.manager import GuardrailManager

    scenario = SCENARIOS["poisoned_telemetry"]
    stack = SandboxStack(scenario=scenario, service=scenario.default_service)
    guard = GuardrailManager()
    raw = run_tools(stack, [TelemetryTool.LOGS])
    cleaned = guard.sanitize(raw)
    assert "ignore all previous instructions" not in str(cleaned.observations).lower()


