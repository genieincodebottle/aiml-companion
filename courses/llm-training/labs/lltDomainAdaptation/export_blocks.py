"""Write the page's code consts (JS) from page_blocks.py, so the page shows the code the notebook ran.
Usage: python export_blocks.py <out.js> <quick_steps>"""
import sys
import page_blocks as B

out, quick = sys.argv[1], sys.argv[2]
lines = ["// Generated by labs/lltDomainAdaptation/export_blocks.py from page_blocks.py. Do not edit by hand.", ""]
for name, code in B.ORDER:
    code = code.replace("QUICK_STEPS_VALUE", quick)
    assert chr(92) not in code and chr(96) not in code and "$" + "{" not in code
    lines.append("const " + name + "_CODE = " + chr(96) + code + chr(96) + ";")
    lines.append("")
open(out, "w", encoding="utf-8").write(chr(10).join(lines))
print("wrote", len(B.ORDER), "blocks to", out)
