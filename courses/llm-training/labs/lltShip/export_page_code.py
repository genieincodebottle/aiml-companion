"""Write the page's code constants (steps/cellNN_stepK.py and the challenge files) as a JS block, and assemble the page
draft: header + constants + body. Page code sits in JS template literals, so this refuses any backslash, backtick or
dollar-brace in the code.

    python export_page_code.py <body.mjs> <out lltShip.mjs>
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
body, out = Path(sys.argv[1]), Path(sys.argv[2])
consts = []
for path in sorted((HERE / "steps").glob("cell*_step*.py")):
    src = path.read_text(encoding="utf-8").rstrip()
    for bad in (chr(92), chr(96), "$" + "{"):
        assert bad not in src, (path.name, bad)
    consts.append("const C" + path.stem[4:6] + " = `" + src + "`;")
for name, var in (("challenge_starter.py", "CH_STARTER"), ("challenge_solution.py", "CH_SOLUTION")):
    src = (HERE / name).read_text(encoding="utf-8").rstrip()
    for bad in (chr(92), chr(96), "$" + "{"):
        assert bad not in src, (name, bad)
    consts.append("const " + var + " = `" + src + "`;")
head = ("// lltShip - Merge, Compress and Serve Your Fine-Tunes (LLM Training Lab, module 22, premium, class C).\n"
        "// Lab page (type 'lab-lesson'). Class C: figures and Run Explorer, no overview. Figures: llt7/lltShip.FIGURES.md;\n"
        "// Try it spec (optional widget): labs/lltShip/TRYIT_SPEC.md.\n"
        "// NUMBERS ARE A CONTRACT. Every number traces to a Run Library file in aiml-companion/courses/llm-training/runs/lltShip/.\n"
        "// Code constants are generated by labs/lltShip/export_page_code.py from steps/ and the challenge files; do not edit them here.\n\n"
        "// BEGIN GENERATED CODE\n")
text = head + "\n\n".join(consts) + "\n// END GENERATED CODE\n\n" + body.read_text(encoding="utf-8")
out.write_text(text, encoding="utf-8")
print("wrote", out, len(text), "chars,", len(consts), "code constants")
