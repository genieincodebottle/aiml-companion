"""Write the lab page's code blocks as JS constants, straight from cells_lab.py, so the page and the notebook
cannot drift. Each shipped code cell is numbered in order (CELL01, CELL02, ...). Fails on a backslash, a backtick
or a dollar-brace, which would break the JS template literal.

  python export_page_code.py <out.mjs>
"""
import os, runpy, sys

HERE = os.path.dirname(os.path.abspath(__file__))
cells = [s for k, s in runpy.run_path(os.path.join(HERE, "cells_lab.py"))["CELLS"] if k == "code"]
out = []
for i, src in enumerate(cells, 1):
    bad = [c for c in (chr(92), chr(96), "$" + "{") if c in src]
    assert not bad, (i, bad)
    out.append("export const CELL%02d = `%s`;" % (i, src))
open(sys.argv[1], "w", encoding="utf-8").write("// Generated by labs/lltQLoRA/export_page_code.py from cells_lab.py. Do not edit.\n" + "\n\n".join(out) + "\n")
print(len(cells), "code cells written")
