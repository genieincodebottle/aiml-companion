"""Build the self-contained Google Cloud job gcp/llt-dpo-exp/run_exp.py from steps/cellNN_stepK.py.

  python make_gcp_job.py
The job runs the page cells in order in one namespace, with the same flags as the Kaggle kernel llt-dpo-exp
(learner defaults, plus RUN_EXPERIMENT = True in steps 10 and 11). --smoke runs every cell at toy size with every RUN_*
flag True (the llt-dpo-smoke kernel), a code-path check of the final code. Resume after a Spot preemption: rerun the
same command; finished arms of step 10 and a finished step 11 are restored from outputs/state.json.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "gcp" / "llt-dpo-exp"
ns = {"__file__": str(HERE / "build_notebook.py")}
exec(compile((HERE / "build_notebook.py").read_text(encoding="utf-8").split("learner = build()")[0], "build_notebook", "exec"), ns)
cells = [(p.stem, p.read_text(encoding="utf-8")) for p in sorted((HERE / "steps").glob("cell*_step*.py"))]
EXP_GCP = dict(ns["EXP"], cell05_step4={"RUN_SFT": "True"}, cell06_step5={"RUN_DPO": "True"})   # no Hub dependency
payload = {"cells": cells, "EXP": EXP_GCP, "ALL_TRUE": ns["ALL_TRUE"], "SMOKE": ns["SMOKE"]}

RUNNER = r'''"""lltDPO exp job for a GPU host (Google Cloud T4 VM llt-c2). Generated by labs/lltDPO/make_gcp_job.py: do not edit.

  python run_exp.py [--smoke] [--out outputs]
Runs the lab page's code cells 1 to 12 in order in one Python namespace, exactly as the notebook does, with
RUN_SFT = True and RUN_DPO = True (it trains its own SFT model and main DPO run, so it needs no file of ours from the Hub),
step 9 off, and steps 10 (IPO, SimPO, ORPO, KTO) and 11 (on-policy pairs) on. --defaults runs the notebook as a learner
gets it (our SFT model and adapter from the Hub, no experiment); --smoke runs everything at toy size. Writes <out>/llt_dpo_<mode>.json (same layout as the
Kaggle kernels' record) and <out>/notebook_stdout.txt. Resume: run the same command again after a preemption.
"""
import json, os, sys, time, platform, argparse
os.environ.setdefault("CUDA_VISIBLE_DEVICES", "0")
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")
PAYLOAD = json.loads(__PAYLOAD__)

ap = argparse.ArgumentParser()
ap.add_argument("--smoke", action="store_true")
ap.add_argument("--defaults", action="store_true", help="the learner notebook as shipped: Hub downloads, no experiments")
ap.add_argument("--out", default="outputs")
args = ap.parse_args()
KERNEL = "smoke-gcp" if args.smoke else ("defaults-gcp" if args.defaults else "exp-gcp")
OUTDIR = os.path.abspath(args.out)
os.makedirs(OUTDIR, exist_ok=True)
STATE = os.path.join(OUTDIR, "state_" + KERNEL + ".json")
WORKDIR = os.path.join(OUTDIR, "work_" + KERNEL)
os.makedirs(WORKDIR, exist_ok=True)
os.chdir(WORKDIR)                      # the cells write sft-model, dpo-check, dpo-trl relative to the working directory


class Tee:
    def __init__(self, path):
        self.f, self.o = open(path, "a"), sys.stdout
    def write(self, x):
        self.o.write(x); self.f.write(x); self.f.flush()
    def flush(self):
        self.o.flush(); self.f.flush()
    def __getattr__(self, name):
        return getattr(self.o, name)


sys.stdout = Tee(os.path.join(OUTDIR, "notebook_stdout_" + KERNEL + ".txt"))
state = json.load(open(STATE)) if os.path.exists(STATE) else {"armsDone": {}, "cell12": None, "restarts": 0}
if os.path.exists(STATE):
    state["restarts"] += 1
print("RESUME" if state["restarts"] else "START", time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "restarts", state["restarts"], flush=True)


def save_state():
    json.dump(state, open(STATE + ".tmp", "w"))
    os.replace(STATE + ".tmp", STATE)


def _clean(o):
    if isinstance(o, dict):
        return {k: _clean(v) for k, v in o.items() if k not in ("dc", "dr")}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    if hasattr(o, "tolist"):
        return o.tolist()
    return o


CELL_PEAK, _PK = {}, {"cur": 0, "hooked": False}


def _peak_hook():
    # the cells reset the CUDA peak counter themselves; record the peak before every reset so no cell peak is lost
    if "torch" not in sys.modules or _PK["hooked"]:
        return
    import torch
    if not torch.cuda.is_available():
        return
    orig = torch.cuda.reset_peak_memory_stats
    def hooked(*a, **k):
        _PK["cur"] = max(_PK["cur"], torch.cuda.max_memory_allocated())
        return orig(*a, **k)
    torch.cuda.reset_peak_memory_stats, _PK["hooked"], _PK["orig"] = hooked, True, orig
    orig()


def _peak_read(stem):
    _peak_hook()
    if _PK["hooked"]:
        import torch
        CELL_PEAK[stem] = round(max(_PK["cur"], torch.cuda.max_memory_allocated()) / 1e9, 2)
        _PK["cur"] = 0
        _PK["orig"]()


flags = PAYLOAD["ALL_TRUE"] if args.smoke else ({} if args.defaults else PAYLOAD["EXP"])
ns = {"__name__": "__main__"}
T_START, CELL_TIMES = time.time(), {}
for stem, src in PAYLOAD["cells"]:
    for flag, value in flags.get(stem, {}).items():
        old = flag + " = False"
        assert old in src, (stem, flag)
        src = src.replace(old, flag + " = " + value, 1)
    if args.smoke:
        for a, b in PAYLOAD["SMOKE"]:
            src = src.replace(a, b)
    if stem == "cell12_step11" and state["cell12"] is not None:
        print("CELL", stem, "restored from state", flush=True)       # step 11 is one unit: samples, labels and both arms
        r = state["cell12"]
        ns["runs"].update(r["runs"]); ns["gens"].update(r["gens"])
        ns["gold"].update({k: ns["np"].array(v) for k, v in r["gold"].items()})
        ns["judge2"].update({k: ns["np"].array(v) for k, v in r["judge2"].items()})
        continue
    t = time.time()
    print("CELL", stem, "start", round(t - T_START, 1), flush=True)
    _peak_hook()
    exec(compile(src, stem, "exec"), ns)
    CELL_TIMES[stem] = round(time.time() - t, 1)
    _peak_read(stem)
    print("CELL", stem, "end", round(time.time() - T_START, 1), flush=True)
    if stem == "cell10_step9":
        # wrap experiment() so finished arms of step 10 survive a preemption; the page code itself is unchanged
        _orig = ns["experiment"]
        def experiment(arms, pairs, ref, _orig=_orig):
            todo = []
            for a in arms:
                done = state["armsDone"].get(a[0])
                if done is None:
                    todo.append(a)
                    continue
                print("arm", a[0], "restored from state", flush=True)
                ns["runs"][a[0]] = done["run"]; ns["gens"][a[0]] = done["gens"]; ns["gold"][a[0]] = ns["np"].array(done["gold"])
                ns["judge2"][a[0]] = ns["np"].array(done["judge2"])
            for a in todo:                      # one arm at a time, so each finished arm is saved before the next starts
                _orig([a], pairs, ref)
                if a[0].startswith(("ipo", "simpo", "orpo", "kto")):
                    state["armsDone"][a[0]] = {"run": _clean(ns["runs"][a[0]]), "gens": ns["gens"][a[0]],
                                               "gold": ns["gold"][a[0]].tolist(), "judge2": ns["judge2"][a[0]].tolist()}
                    save_state()
        ns["experiment"] = experiment
    if stem == "cell12_step11" and flags.get(stem, {}).get("RUN_EXPERIMENT") == "True":
        pre = ("onpolicy", "offline")
        keys = [k for k in ns["runs"] if k.startswith(pre)]
        state["cell12"] = {"runs": _clean({k: ns["runs"][k] for k in keys}),
                           "gens": {k: ns["gens"][k] for k in ns["gens"] if k.startswith(pre)},
                           "gold": {k: ns["gold"][k].tolist() for k in ns["gold"] if k.startswith(pre)},
                           "judge2": {k: ns["judge2"][k].tolist() for k in ns["judge2"] if k.startswith(pre)}}
        save_state()

import torch, transformers, trl, peft, datasets
rec = {"kernel": KERNEL, "host": "gcp", "gpu": torch.cuda.get_device_name(0), "restarts": state["restarts"],
       "env": {"python": platform.python_version(), "torch": torch.__version__, "cuda": torch.version.cuda,
               "transformers": transformers.__version__, "trl": trl.__version__, "peft": peft.__version__,
               "datasets": datasets.__version__},
       "cellTimes": CELL_TIMES, "runs": _clean(ns["runs"]), "totalSec": round(time.time() - T_START, 1),
       "gens": _clean(ns.get("gens", {})), "gold": _clean(ns.get("gold", {})), "judge2": _clean(ns.get("judge2", {})),
       "cellPeakGB": CELL_PEAK}
if "final" in ns:
    rec["finalHeld"] = {"dc": ns["final"]["dc"].tolist(), "dr": ns["final"]["dr"].tolist()}
json.dump(rec, open(os.path.join(OUTDIR, "llt_dpo_" + KERNEL + ".json"), "w"), indent=1)
print("RECORD written", rec["totalSec"], flush=True)
'''

OUT.mkdir(parents=True, exist_ok=True)
(OUT / "run_exp.py").write_text(RUNNER.replace("__PAYLOAD__", repr(json.dumps(payload))), encoding="utf-8")
print("wrote", OUT / "run_exp.py")
